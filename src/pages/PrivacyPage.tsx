import { Seo } from '../components/Seo';
import { site } from '../config/site';
import { formReady } from '../lib/submit';
import { PageHead } from './PageHead';

/*
 * Базовый текст политики. Перед запуском продаж его должен проверить юрист и дополнить
 * реквизитами оператора (site.legal) — без них политика неполная, и сайт об этом честно пишет.
 */
export function PrivacyPage() {
  const l = site.legal;
  const operator = [l.name, l.inn && `ИНН ${l.inn}`, l.ogrn && `${l.ogrnLabel} ${l.ogrn}`, l.address].filter(Boolean).join(', ');
  return (
    <>
      <Seo title="Политика конфиденциальности" description={`Как сайт «${site.name}» обрабатывает персональные данные из заявок.`} />
      <PageHead title="Политика конфиденциальности" />
      <section className="section" style={{ paddingTop: 'var(--space-6)' }}>
        <div className="container prose">
          <h2>1. Оператор</h2>
          <p>{operator ? `Оператор персональных данных: ${operator}.` : 'Реквизиты оператора персональных данных будут опубликованы на этой странице до начала приёма заявок.'}{site.contacts.email && ` Связаться по вопросам обработки данных: ${site.contacts.email}.`}</p>
          <h2>2. Какие данные мы получаем</h2>
          <p>Только то, что вы указываете в форме: имя или название компании, email, телефон, комментарий и список выбранных позиций.</p>
          <h2>3. Зачем</h2>
          <p>Чтобы ответить на заявку или вопрос: подготовить расчёт, уточнить наличие и условия поставки. Мы не используем данные для рассылок без отдельного согласия и не передаём их третьим лицам, кроме случаев, нужных для ответа.</p>
          <h2>4. Как передаются данные</h2>
          <p>{formReady()
            ? 'Форма отправляет заявку через сервис доставки писем на почту продавца по защищённому соединению (HTTPS).'
            : 'Сейчас форма на сайте ничего не отправляет автоматически: она готовит текст заявки, который вы сами отправляете по почте или в мессенджер.'}</p>
          <h2>5. Избранное и список заявки</h2>
          <p>Избранное и список заявки хранятся только в вашем браузере (localStorage) и никуда не передаются. Их можно удалить, очистив данные сайта в браузере.</p>
          <h2>6. Ваши права</h2>
          <p>Вы можете запросить уточнение, изменение или удаление своих данных, а также отозвать согласие на обработку — ответив на письмо менеджера или через контакты на сайте.</p>
        </div>
      </section>
    </>
  );
}
